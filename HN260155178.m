% 1.3 CALIBRATION ON NEANDERTHALS
% =========================================================================
clear; clc; close all;

% PHYSICAL PARAMETERS
p.P_N = 150;          % Neanderthal energetic cost (W)
p.P_H = p.P_N - 15;     % Human energetic cost (W)
p.E_tot = 1e6;        % Energía total disponible en el hábitat local (W)

% INTRINSIC GROWTH RATES
p.r_H = 0.010;        % Human growth (small value adjusted to the millenium scales from the data)
p.r_N = 0.002;        % Lower than human growth

% COMPETITION COEFFICIENTS (Cognitive niche)
p.beta_HN = 2.2;      % Resource competition H over N
p.beta_NH = 0.8;      % Resource competition N over H
p.gamma_HN = 0.0000005; % Lethality competition H over N
p.gamma_NH = 0.0000001; % Lethality competition N over H


% INITIAL CONDITIONS (First contact situation)
N0 = p.E_tot / p.P_N;   % Neanderthals start in equilibrium (the largest population sustained by the total energy available)
H0 = 0.01 * N0;     % Initial human invasion (1% of Neanderthal population)
y0 = [H0; N0];

% ODEs SYSTEM

% Definition of the function that contains system of ODEs which model the
% interactions.
% y(1) = H (Human), y(2) = N (Neanderthal)
ode_sys = @(t, y) [
    p.r_H * y(1) * (1 - (p.P_H * y(1) + p.beta_NH * p.P_N * y(2)) / p.E_tot) - p.gamma_NH * y(1) * y(2);
    p.r_N * y(2) * (1 - (p.P_N * y(2) + p.beta_HN * p.P_H * y(1)) / p.E_tot) - p.gamma_HN * y(1) * y(2)
];

% RESOLUTION WITH ode45 (up to 6000 years)
tspan = [0 6000];
[t, y] = ode45(ode_sys, tspan, y0); % solves the system
H = y(:,1); % Evolution of human population
N = y(:,2); % Evolution of Neanderthal population

% EXTINCTION TIME
% We define "extintion" as the moment when N drops below 1% of the original
extinction_idx = find(N < 0.01*N0, 1); % Find the first index where the previous condition is met

% According to extinction happening or not, we define two possible
% outcomes:
if isempty(extinction_idx)
    fprintf('The Neanderthal population hasn´t extinguished inside the established time range (%.0f years).\n', tspan(2));
    extinction_time = NaN;
else
    extinction_time = t(extinction_idx);
    fprintf('Neanderthal population extinction time: %.0f years.\n', extinction_time);
end
fprintf('Coexistence range: 1400 - 5400 years.\n'); % Extracted from the data

% GRAPH 1: EVOLUTION OVER TIME

% We plot two curves representing the evolution over time of both
% populations with a vertical line to place exactly the moment of
% extinction
figure('Color', 'w', 'Position', [100, 100, 1000, 400]);
subplot(1,2,1);
plot(t, H, 'b-', 'LineWidth', 2); hold on;
plot(t, N, 'r-', 'LineWidth', 2);

if ~isnan(extinction_time)
    xline(extinction_time, 'k--', 'LineWidth', 1.5);
    text(extinction_time + 100, N0*0.5, sprintf('Extinction: %.0f years', extinction_time), 'FontWeight', 'bold');
end

xlabel('Time (Years)'); ylabel('Population');
title('Competitive Exclusion Dynamic');
legend('Humans (H)', 'Neanderthals (N)', 'Location', 'best');
grid on;

% GRAPH 2: PHASE-SPACE DIAGRAM

% To visualize the system's global dynamics, the phase-space diagram was generated by computing a directional vector field
% over a discrete grid of population states. Using a mesh grid, we defined a matrix of human and Neanderthal population
% coordinates. For each coordinate pair, the instantaneous rates of change were evaluated iteratively through our coupled ODE
% system to determine the ecosystem's local trajectory. The resulting directional vectors were then normalized to a uniform
% length to prevent visual distortion from extreme magnitude variations
subplot(1,2,2);
plot(H, N, 'k-', 'LineWidth', 2); hold on;
plot(H(1), N(1), 'go', 'MarkerSize', 8, 'MarkerFaceColor', 'g'); % Start
plot(H(end), N(end), 'ro', 'MarkerSize', 8, 'MarkerFaceColor', 'r'); % Finish

% DIRECTION FIELDS VECTOR (QUIVER PLOT)
h_vals = linspace(0, max(H)*1.1, 15);
n_vals = linspace(0, max(N)*1.1, 15);
[H_grid, N_grid] = meshgrid(h_vals, n_vals);
dH_grid = zeros(size(H_grid)); dN_grid = zeros(size(N_grid));

for i = 1:numel(H_grid)
    dy = ode_sys(0, [H_grid(i); N_grid(i)]);
    dH_grid(i) = dy(1); dN_grid(i) = dy(2);
end

L = sqrt(dH_grid.^2 + dN_grid.^2);
L(L==0) = 1; % avoid dividing by 0
quiver(H_grid, N_grid, dH_grid./L, dN_grid./L, 0.5, 'Color', [0.5 0.5 0.5]);

xlabel('Human Population (H)'); ylabel('Neanderthal Population (N)');
title('Phase-Space Diagram');

set(gcf, 'Color', 'w');

% FIRST GRAPH
subplot(1, 2, 1);
set(gca, 'Color', 'w', 'XColor', 'k', 'YColor', 'k', 'GridColor', 'k');
title('Competitive Exclusion Dynamic', 'Color', 'k');
xlabel('Time (Years)', 'Color', 'k');
ylabel('Population', 'Color', 'k');
legend('Humans (H)', 'Neanderthals (N)', 'Color', 'w', 'TextColor', 'k');

% SECOND GRAPH
subplot(1, 2, 2);
set(gca, 'Color', 'w', 'XColor', 'k', 'YColor', 'k', 'GridColor', 'k');
title('Phase-Space Diagram', 'Color', 'k');
xlabel('Human Population (H)', 'Color', 'k');
ylabel('Neanderthal Population (N)', 'Color', 'k');

grid on;